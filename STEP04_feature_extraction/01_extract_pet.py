"""Extract the six PET composites and ordered 82 unilateral gray-matter means."""
from pathlib import Path
import argparse
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from step_support import ROOT, read_json, write_json, new_output, require_review
from pet_vns_prediction.features import normalize_pet, extract_pet_features, roi_stats


def extract_roi82(pet, labels, roi_config, feature_config):
    import numpy as np
    pairs = roi_config['bilateral_pairs']
    if len(pairs) != 41:
        raise ValueError('The fixed 82-region panel requires exactly 41 bilateral gray-matter pairs')
    if len({int(v[side]) for v in pairs.values() for side in ('left','right')}) != 82:
        raise ValueError('All 82 unilateral labels must be distinct')
    rules = feature_config['voxel_and_missingness_rules']
    args = (rules['minimum_label_voxels_hard'], rules['label_voxels_attention_range'][1],
            rules['valid_pet_fraction_pass_minimum'], rules['valid_pet_fraction_attention_minimum'])
    names, values, details = [], [], {}
    for pair in sorted(pairs):
        for side, key in (('L', 'left'), ('R', 'right')):
            name = f'{side}_{pair}'
            info = roi_stats(np.asarray(pet), np.asarray(labels) == int(pairs[pair][key]), *args)
            names.append(name)
            values.append(info['mean'])
            details[name] = info
    if len(set(names)) != 82:
        raise ValueError('Duplicated regional names')
    return names, values, details


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--subject', required=True)
    ap.add_argument('--study-id', help='Explicit verified analysis key; default removes only the sub- naming prefix')
    ap.add_argument('--pet', type=Path, required=True, help='Unnormalized directRigid_pet.nii.gz on the 2-mm grid')
    ap.add_argument('--labels', type=Path, required=True)
    ap.add_argument('--brainmask', type=Path, required=True)
    ap.add_argument('--reference', choices=['supraGM','wholeBrain','cerebellarCortex'], default='supraGM')
    ap.add_argument('--feature-config', type=Path, default=ROOT/'configs/features.json')
    ap.add_argument('--roi82-config', type=Path, default=ROOT/'configs/roi82.json')
    ap.add_argument('--qc-table', type=Path, required=True)
    ap.add_argument('--output', type=Path, required=True)
    a = ap.parse_args()
    require_review(a.qc_table, a.subject, 'segmentation_review')
    require_review(a.qc_table, a.subject, 'registration_review')
    require_review(a.qc_table, a.subject, 'coverage_review')
    import nibabel as nib
    import numpy as np
    images = [nib.as_closest_canonical(nib.load(str(p))) for p in (a.pet, a.labels, a.brainmask)]
    first = images[0]
    if len(first.shape) != 3 or not np.allclose(first.header.get_zooms()[:3], [2,2,2], rtol=0, atol=1e-4):
        raise ValueError('Expected a three-dimensional 2-mm isotropic PET grid')
    if any(i.shape != first.shape or not np.allclose(i.affine, first.affine, atol=1e-5) for i in images[1:]):
        raise ValueError('PET, segmentation and brain mask must share geometry')
    pet, labels, mask = [np.asanyarray(i.dataobj) for i in images]
    config = read_json(a.feature_config)
    normalized, norm_qc = normalize_pet(pet, labels, mask, a.reference, config)
    if not norm_qc['reference_intensity_gate_pass']:
        raise ValueError('Reference/coverage numerical gate failed; inspect source and do not force extraction')
    result = extract_pet_features(normalized, labels, config)
    names, values, details = extract_roi82(normalized, labels, read_json(a.roi82_config), config)
    primary = {key: value['value'] for key, value in result['primary_features'].items()}
    canonical = {f'pet_{a.reference}__{key}': value for key, value in primary.items()}
    out = new_output(a.output)
    header = first.header.copy()
    header.set_data_dtype(np.float32)
    nib.save(nib.Nifti1Image(normalized, first.affine, header), str(out/'normalized_pet.nii.gz'))
    payload = {'subject': a.subject, 'study_id': a.study_id if a.study_id is not None else a.subject.removeprefix('sub-'),
               'reference': a.reference, 'primary_features': primary, 'features': canonical,
               'canonical_features': canonical, 'roi82_features': names, 'roi82_values': values,
               'roi82_details': details, 'pair_results': result['pair_results'],
               'qc': {'normalization': norm_qc,
                      'primary_feature_status': result['overall_primary_feature_qc_status'],
                      'roi82_missing_values': sum(value is None for value in values),
                      'visual_review_source': 'provided manual QC table; not generated by extraction'}}
    write_json(out/'pet_features.json', payload)
    print(f'Wrote six composites and {len(names)} regional values; missing and attention flags retained.')


if __name__ == '__main__':
    main()
